def get_json(url, tries=4):
    last = None
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=120) as resp:
                return json.loads(resp.read())
        except Exception as e:  # noqa: BLE001 — retry any transport hiccup
            last = e
            time.sleep(2 * (attempt + 1))
    raise RuntimeError(f"GET failed after {tries} tries: {url} ({last})")


def fetch_all(url):
    """Follow `next` links until exhausted; return the concatenated results."""
    out = []
    while url:
        payload = get_json(url)
        out.extend(payload.get("results") or [])
        nxt = payload.get("next")
        # Open5e sometimes hands back http:// next-links; keep https.
        url = nxt.replace("http://", "https://") if nxt else None
        sys.stderr.write(f"    …{len(out)}\n")
    return out


