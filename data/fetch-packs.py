def strip_md(s):
    return re.sub(r"\*\*_?|_?\*\*", "", s or "").replace("**", "").strip()


def md_traits(md):
    """Split a v1 markdown trait blob (**_Name._** text …) into display strings."""
    out = []
    if not md:
        return out
    parts = re.split(r"\*\*_?\s*([^*_]+?)\.?\s*_?\*\*", md)
    for i in range(1, len(parts) - 1, 2):
        name = parts[i].strip()
        text = first_sentence(parts[i + 1].strip(), 220)
        if name:
            out.append(f"{name}. {text}" if text else name)
    return out


def v1_race(r):
    asi_text = strip_md(r.get("asi_desc") or "").replace("Ability Score Increase.", "").strip()
    subraces = []
    for sr in r.get("subraces") or []:
        subraces.append({
            "name": sr.get("name", ""),
            "asiText": strip_md(sr.get("asi_desc") or "").replace("Ability Score Increase.", "").strip(),
            "blurb": first_sentence(sr.get("desc") or ""),
            "traits": md_traits(sr.get("traits") or ""),
        })
    traits = md_traits(r.get("traits") or "")
    for extra in ("vision", "alignment"):
        t = md_traits(r.get(extra) or "")
        traits.extend(t)
    speed = r.get("speed") or {}
    return {
        "name": r["name"],
        "size": r.get("size_raw") or "Medium",
        "speed": speed.get("walk", 30) if isinstance(speed, dict) else 30,
        "asiText": asi_text or "—",
        "blurb": first_sentence(r.get("desc") or ""),
        "traits": traits,
        "subraces": subraces,
    }


