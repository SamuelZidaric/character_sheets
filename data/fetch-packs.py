def fmt_money(c):
    try:
        v = float(c or 0)
    except (TypeError, ValueError):
        return "—"
    if v <= 0:
        return "—"
    return (f"{v:.2f}".rstrip("0").rstrip(".")) + " gp"


def fmt_weight(w):
    try:
        v = float(w or 0)
    except (TypeError, ValueError):
        return "—"
    return (f"{v:.3f}".rstrip("0").rstrip(".") + " lb") if v > 0 else "—"


