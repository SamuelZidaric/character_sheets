def v2_weapon(w, item_lookup):
    props = []
    for p in w.get("properties") or []:
        prop = p.get("property") or {}
        pname = prop.get("name", "")
        if prop.get("type") == "Mastery":
            pname += " (Mastery)"
        if p.get("detail"):
            pname += f" ({p['detail']})"
        if pname:
            props.append(pname)
    cat = ("Simple" if w.get("is_simple") else "Martial") + (" Ranged" if (w.get("range") or 0) > 5 else " Melee")
    dmg = f"{w.get('damage_dice') or ''} {nm(w.get('damage_type')).lower()}".strip()
    it = item_lookup.get(w["name"].lower(), {})
    return {
        "name": w["name"],
        "cat": cat,
        "dmg": dmg or "—",
        "props": ", ".join(props) if props else "—",
        "weight": it.get("weight", "—"),
        "cost": it.get("cost", "—"),
    }


