# ─── Fetch drivers ──────────────────────────────────────────────────────────

def fetch_v1_packs():
    """Fetch all v1 endpoints (all documents), group by document, transform."""
    packs = {}
    licenses = {}

    def one(ep):
        sys.stderr.write(f"  v1/{ep}:\n")
        return ep, fetch_all(f"{API1}/{ep}/?limit=500")

    with ThreadPoolExecutor(max_workers=4) as ex:
        results = dict(ex.map(one, V1_ENDPOINTS))

    for ep, rows in results.items():
        cat = V1_ENDPOINTS[ep]
        tf = V1_TRANSFORMS[ep]
        for raw in rows:
            slug = raw.get("document__slug") or ""
            if slug in ("", "wotc-srd") or slug not in PACK_INFO:
                continue  # core SRD lives in srd-bulk.js; unknown docs skipped
            if slug not in licenses and raw.get("document__license_url"):
                licenses[slug] = raw["document__license_url"]
            entry = tf(raw)
            entry["source"] = slug
            entry["pack"] = slug
            packs.setdefault(slug, {}).setdefault(cat, []).append(entry)
    return packs, licenses


def fetch_v2_srd2024():
    key = "srd-2024"

    def doc_key(r):
        d = r.get("document")
        if isinstance(d, dict):
            return d.get("key") or ""
        return str(d or "").rstrip("/").rsplit("/", 1)[-1]  # plain key or URL form

    def grab(ep):
        sys.stderr.write(f"  v2/{ep}:\n")
        # Filter param naming is inconsistent across v2 endpoints (magicitems
        # honours `document`, creatures honours `document__key`); send both —
        # each endpoint applies the one it knows and ignores the other.
        rows = fetch_all(f"{API2}/{ep}/?document={key}&document__key={key}&limit=500")
        # Belt-and-braces: verify per entry in case an endpoint ignores both.
        return [r for r in rows
                if doc_key(r) == key or str(r.get("key", "")).startswith(key)]

    eps = ["creatures", "spells", "magicitems", "items", "species", "classes",
           "backgrounds", "feats", "weapons", "armor", "rules"]
    with ThreadPoolExecutor(max_workers=4) as ex:
        raw = dict(zip(eps, ex.map(grab, eps)))

    # cost/weight live on /v2/items — join onto weapons & armor by name
    item_lookup = {}
    for it in raw["items"]:
        w = it.get("weight")
        c = it.get("cost")
        item_lookup[it["name"].lower()] = {
            "weight": (w.rstrip("0").rstrip(".") + " lb") if isinstance(w, str) and float(w or 0) > 0 else "—",
            "cost": (c.rstrip("0").rstrip(".") + " gp") if isinstance(c, str) and float(c or 0) > 0 else "—",
        }

    species = raw["species"]
    classes = raw["classes"]
    data = {
        "monsters":    [v2_creature(m) for m in raw["creatures"]],
        "spells":      [v2_spell(s) for s in raw["spells"]],
        "items":       [v2_magicitem(i) for i in raw["magicitems"]],
        "gear":        [v2_gear(i) for i in raw["items"]],
        "races":       [v2_species(sp, species) for sp in species if not sp.get("is_subspecies")],
        "classes":     [v2_class(c, classes) for c in classes if not c.get("subclass_of")],
        "backgrounds": [v2_background(b) for b in raw["backgrounds"]],
        "feats":       [v2_feat(f) for f in raw["feats"]],
        "weapons":     [v2_weapon(w, item_lookup) for w in raw["weapons"]],
        "armor":       [v2_armor(a, item_lookup) for a in raw["armor"]],
        "sections":    [v2_rule(r) for r in raw["rules"]],
    }
    for cat, rows in data.items():
        for e in rows:
            e["source"] = key
            e["pack"] = key
    return {key: data}


def existing_item_names():
    """Names of magic items already shipped in srd-bulk.js (the v1 5.1 import),
    so the srd-2014-x variant pack only adds genuinely new entries."""
    bulk = HERE / "srd-bulk.js"
    names = set()
    if bulk.exists():
        txt = bulk.read_text(encoding="utf-8")
        m = re.search(r"window\.SRD_BULK = (\{.*?\});\n\n\(function", txt, re.DOTALL)
        if m:
            try:
                names = {e["name"].lower() for e in json.loads(m.group(1)).get("items", [])}
            except Exception:
                pass
    return names


def fetch_srd2014_extras():
    """Official 5.1 content the v1 API never exposed: mundane gear, equipment
    sets, and the fully-enumerated magic-item variants."""
    key = "srd-2014"

    def doc_key(r):
        d = r.get("document")
        if isinstance(d, dict):
            return d.get("key") or ""
        return str(d or "").rstrip("/").rsplit("/", 1)[-1]

    def grab(ep):
        sys.stderr.write(f"  v2/{ep} ({key}):\n")
        rows = fetch_all(f"{API2}/{ep}/?document={key}&document__key={key}&limit=500")
        return [r for r in rows if doc_key(r) == key or str(r.get("key", "")).startswith("srd_")]

    gear = [v2_gear(i) for i in grab("items")]
    # Equipment packs exist both as items (cost/weight) and itemsets (contents);
    # merge contents into the matching item, append only true standalone sets.
    by_name = {g["name"].lower(): g for g in gear}
    for s in grab("itemsets"):
        e = v2_itemset(s)
        hit = by_name.get(e["name"].lower())
        if hit:
            hit["desc"] = (hit["desc"] + "\n\n" if hit["desc"] else "") + e["desc"]
            if not hit["blurb"]:
                hit["blurb"] = e["blurb"]
        else:
            gear.append(e)
    have = existing_item_names()
    variants = [v2_magicitem(i) for i in grab("magicitems")]
    variants = [v for v in variants if v["name"].lower() not in have]
    sys.stderr.write(f"  srd-2014-x: {len(gear)} gear, {len(variants)} new item variants\n")

    data = {"gear": gear, "items": variants}
    for cat, rows in data.items():
        for e in rows:
            e["source"] = "srd-2014"
            e["pack"] = "srd-2014-x"
    return {"srd-2014-x": data}


